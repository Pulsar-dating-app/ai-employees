export type CountryCode = (typeof COUNTRY_CODES)[number];

const CODE_SET = new Set<string>(COUNTRY_CODES);

export function isCountryCode(value: string): value is CountryCode {
  return CODE_SET.has(value);
}

// Localised country name for a code, using the runtime's CLDR data. Returns
// null when the code isn't one `Intl.DisplayNames` recognises (it echoes the
// code back in that case) so callers can drop it from a picker.
export function countryName(code: string, locale: string): string | null {
  try {
    const name = new Intl.DisplayNames([locale], { type: "region" }).of(code);
    return name && name !== code ? name : null;
  } catch {
    return null;
  }
}
